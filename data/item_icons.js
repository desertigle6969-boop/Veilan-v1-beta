function getItemIcon(itemId) {
  // 1. Прямая привязка
  if (ITEM_ICONS[itemId]) return ITEM_ICONS[itemId];

  // 2. Fallback: по префиксу и тиру
  var m = itemId.match(/^(helm|chest|legs|cloak)_(light|med|heavy|vh)_?(\d+)?$/);
  if (!m) {
    // Старый формат: helm_cloth, chest_iron и т.п.
    if (itemId.indexOf('helm_') === 0) return 'sprites/icons/helmet/BTN_Armor_Head13.png';
    if (itemId.indexOf('chest_') === 0) return 'sprites/icons/chest/BTN_Armor_Chest25.png';
    if (itemId.indexOf('legs_') === 0) return 'sprites/icons/legs/BTN_Armor_Legs01.png';
    if (itemId.indexOf('cloak_') === 0) return 'sprites/icons/cloak/BTN_Armor_Back01.png';
    return null;
  }

  var slot = m[1];       // helm | chest | legs | cloak
  var category = m[2];   // light | med | heavy | vh
  var tier = parseInt(m[3] || '1', 10);

  // Номера иконок по категории
  // helmet: 13-21 (9 свободных)
  // chest: 25-44 (20 свободных)
  // legs: 1-40 (все)
  if (slot === 'helm') {
    var helmMap = {
      'light': 13, 'med': 14, 'heavy': 15, 'vh': 16
    };
    var base = helmMap[category] || 13;
    var num = base + (tier - 1);
    if (num > 21) num = 21;
    return 'sprites/icons/helmet/BTN_Armor_Head' + (num < 10 ? '0' : '') + num + '.png';
  }

  if (slot === 'chest') {
    var chestMap = { 'light': 25, 'med': 30, 'heavy': 35, 'vh': 40 };
    var cbase = chestMap[category] || 25;
    var cnum = cbase + (tier - 1);
    if (cnum > 45) cnum = 45;
    return 'sprites/icons/chest/BTN_Armor_Chest' + (cnum < 10 ? '0' : '') + cnum + '.png';
  }

  if (slot === 'legs') {
    // Используем именованные иконки
    var legsList = [
      'BTN_armor_hose_i00.png',
      'BTN_armor_leather_hose_i00.png',
      'BTN_armor_chain_gaiters_i00.png',
      'BTN_armor_iron_plate_gaiters_i00.png',
      'BTN_armor_mithril_gaiters_i00.png',
      'BTN_armor_plate_gaiters_i00.png',
      'BTN_armor_mithril_banded_gaiters_i00.png',
      'BTN_armor_tempered_mithril_gaiters_i00.png'
    ];
    var legsByCat = { 'light': 0, 'med': 1, 'heavy': 2, 'vh': 4 };
    var lnum = (legsByCat[category] || 0) + (tier - 1);
    if (lnum >= legsList.length) lnum = legsList.length - 1;
    return 'sprites/icons/legs/' + legsList[lnum];
  }

  return null;
}

window.ItemIcons = {
  ITEM_ICONS,
  getItemIcon
};
